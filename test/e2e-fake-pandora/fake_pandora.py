# 1x1 PNG used for album art.
PNG = bytes.fromhex(
    "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c489"
    "0000000d49444154789c6360f8cfc0f01f0005000201a3b6bf9f0000000049454e44ae426082")


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "FakePandora/1"

    def log_message(self, fmt, *args):
        self.server.state.log("%s %s" % (self.address_string(), fmt % args))

    # -- plumbing -----------------------------------------------------------
    def _send(self, code, body, ctype, extra=()):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Accept-Ranges", "bytes")
        for k, v in extra:
            self.send_header(k, v)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _json(self, obj):
        self._send(200, json.dumps(obj).encode(), "text/plain; charset=utf-8")

    def do_CONNECT(self):
        """Proxy CONNECT used for pianobar's HTTPS requests: upgrade to TLS."""
        state = self.server.state
        if state.tls is None:
            self.send_error(501, "TLS not configured (--cert/--key)")
            return
        self.send_response(200, "Connection established")
        self.end_headers()
        self.wfile.flush()
        try:
            tls_sock = state.tls.wrap_socket(self.connection, server_side=True)
        except (ssl.SSLError, OSError) as exc:
            state.log("TLS handshake failed: %s" % exc)
            self.close_connection = True
            return
        # Serve HTTP on the encrypted tunnel with a nested handler.
        try:
            Handler(tls_sock, self.client_address, self.server)
        finally:
            self.close_connection = True

    def do_HEAD(self):
        self.do_GET()

    def do_GET(self):
        path = urlsplit(self.path).path
        if path == "/healthz":
            self._send(200, b"ok\n", "text/plain")
        elif path.startswith("/audio/"):
            self._serve_audio()
        elif path.startswith("/art/"):
            self._send(200, PNG, "image/png")
        elif path.startswith("/detail/"):
            self._send(200, b"fake detail\n", "text/plain")
        else:
            self.server.state.log("UNKNOWN PATH GET %s" % self.path)
            self._send(404, b"not found\n", "text/plain")

    def _serve_audio(self):
        data = self.server.state.audio
        rng = self.headers.get("Range")
        if rng and rng.startswith("bytes="):
            first, _, last = rng[6:].partition("-")
            start = int(first) if first else 0
            end = int(last) if last else len(data) - 1
            end = min(end, len(data) - 1)
            if start >= len(data):
                self._send(416, b"", "audio/mpeg",
                           [("Content-Range", "bytes */%d" % len(data))])
                return
            chunk = data[start:end + 1]
            self._send(206, chunk, "audio/mpeg",
                       [("Content-Range", "bytes %d-%d/%d" % (start, end, len(data)))])
        else:
            self._send(200, data, "audio/mpeg")

    def do_POST(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        url = urlsplit(self.path)
        if not url.path.startswith("/services/json"):
            self.server.state.log("UNKNOWN PATH POST %s" % self.path)
            self._send(404, b"not found\n", "text/plain")
            return
        query = {k: v[0] for k, v in parse_qs(url.query).items()}
        method = query.get("method")
        state = self.server.state
        text = raw.decode("utf-8", "replace").strip()
        try:
            if method == "auth.partnerLogin":
                body = json.loads(text)           # sent unencrypted
            else:
                plain = state.cipher_in.decrypt(bytes.fromhex(text))
                body = json.loads(plain.rstrip(b"\0").decode("utf-8"))
        except ValueError as exc:
            state.log("BAD REQUEST for %s: %s (body=%r)" % (method, exc, text[:80]))
            self._json(fail(ERR_INTERNAL, "fake-pandora: undecodable request"))
            return
        reply = self.server.api.dispatch(method, query, body)
        state.log("%s -> %s" % (method, reply.get("stat")))
        self._json(reply)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=0, help="0 = pick a free port")
    ap.add_argument("--port-file", help="write the bound port here once listening")
    ap.add_argument("--cert", help="PEM certificate for the HTTPS tunnel")
    ap.add_argument("--key", help="PEM private key for --cert")
    ap.add_argument("--audio", default=str(Path(__file__).resolve().parents[1]
                                           / "fixtures" / "tone.mp3"))
    ap.add_argument("--audio-repeat", type=int, default=60,
                    help="repeat the 0.5 s fixture this many times per track (default 60 = 30 s)")
    ap.add_argument("--outkey", required=True,
                    help="pianobar encrypt_password (decrypts its requests)")
    ap.add_argument("--inkey", required=True,
                    help="pianobar decrypt_password (encrypts syncTime)")
    ap.add_argument("--partner-user", default="e2e-partner")
    ap.add_argument("--partner-password", default="e2e-partner-password")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)

    _selftest()
    if args.selftest:
        print("blowfish ok")
        return 0

    state = State(args)
    state.tls = None
    if args.cert:
        state.tls = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        state.tls.load_cert_chain(args.cert, args.key)

    httpd = ThreadingHTTPServer((args.host, args.port), Handler)
    httpd.daemon_threads = True
    httpd.state = state
    port = httpd.server_address[1]
    httpd.api = Api(state, "http://%s:%d" % (args.host, port))
    if args.port_file:
        Path(args.port_file).write_text("%d\n" % port)
    state.log("listening on %s:%d" % (args.host, port))
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
