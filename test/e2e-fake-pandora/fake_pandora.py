# --------------------------------------------------------------------------
# Blowfish (ECB, big-endian blocks, as libgcrypt's GCRY_CIPHER_BLOWFISH)
# --------------------------------------------------------------------------

def _pi_hex_words(count):
    """Return the first `count` 32-bit words of the fractional part of pi."""
    bits = count * 32
    guard = 64
    one = 1 << (bits + guard)

    def arctan_inv(x):
        # arctan(1/x) * one, by the Taylor series.
        total = term = one // x
        x2 = x * x
        n = 1
        sign = -1
        while term:
            term //= x2
            n += 2
            total += sign * (term // n)
            sign = -sign
        return total

    pi = 4 * (4 * arctan_inv(5) - arctan_inv(239))
    frac = (pi - 3 * one) >> guard  # fractional part, `bits` bits
    return [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(count)]


class Blowfish:
    _words = None

    def __init__(self, key):
        if Blowfish._words is None:
            Blowfish._words = _pi_hex_words(18 + 4 * 256)
        words = Blowfish._words
        self.p = list(words[:18])
        self.s = [list(words[18 + 256 * i:18 + 256 * (i + 1)]) for i in range(4)]
        key = bytes(key)
        j = 0
        for i in range(18):
            data = 0
            for _ in range(4):
                data = (data << 8) | key[j]
                j = (j + 1) % len(key)
            self.p[i] ^= data
        left = right = 0
        for i in range(0, 18, 2):
            left, right = self._encrypt_block(left, right)
            self.p[i], self.p[i + 1] = left, right
        for box in self.s:
            for i in range(0, 256, 2):
                left, right = self._encrypt_block(left, right)
                box[i], box[i + 1] = left, right

    def _f(self, x):
        s = self.s
        return ((((s[0][x >> 24] + s[1][(x >> 16) & 255]) & 0xFFFFFFFF)
                 ^ s[2][(x >> 8) & 255]) + s[3][x & 255]) & 0xFFFFFFFF

    def _encrypt_block(self, left, right):
        p = self.p
        for i in range(16):
            left ^= p[i]
            right ^= self._f(left)
            left, right = right, left
        left, right = right, left
        right ^= p[16]
        left ^= p[17]
        return left, right

    def _decrypt_block(self, left, right):
        p = self.p
        for i in range(17, 1, -1):
            left ^= p[i]
            right ^= self._f(left)
            left, right = right, left
        left, right = right, left
        right ^= p[1]
        left ^= p[0]
        return left, right

    def _apply(self, data, block_fn):
        out = bytearray()
        for i in range(0, len(data), 8):
            left = int.from_bytes(data[i:i + 4], "big")
            right = int.from_bytes(data[i + 4:i + 8], "big")
            left, right = block_fn(left, right)
            out += left.to_bytes(4, "big") + right.to_bytes(4, "big")
        return bytes(out)

    def encrypt(self, data):
        data = bytes(data)
        data += b"\0" * (-len(data) % 8)
        return self._apply(data, self._encrypt_block)

    def decrypt(self, data):
        return self._apply(bytes(data), self._decrypt_block)


def _selftest():
    # Eric Young's published vector: key 0000000000000000, zero block.
    cipher = Blowfish(bytes(8))
    got = cipher.encrypt(bytes(8)).hex()
    assert got == "4ef997456198dd78", got
    assert cipher.decrypt(bytes.fromhex(got)) == bytes(8)


