#!/usr/bin/env python3
"""Fake Pandora JSON API for end-to-end tests of the real pianobar binary.

Standard library only. The fake speaks the subset of the Pandora JSON API that
pianobar uses at startup and while the web UI E2E specs drive it:

  auth.partnerLogin, auth.userLogin, user.getStationList, station.getPlaylist,
  station.addFeedback, station.deleteFeedback, user.sleepSong,
  user.getSettings, user.changeSettings, station.getStation,
  station.renameStation, station.deleteStation, station.createStation,
  music.search, bookmark.add{Song,Artist}Bookmark, track.explainTrack.

Anything else is logged on stderr as "UNKNOWN METHOD" and answered with a
Pandora-style error body ({"stat":"fail","code":...}).

How pianobar is pointed at it
-----------------------------
pianobar sends "secure" requests (logins, getPlaylist, ...) over HTTPS to
rpc_host:rpc_tls_port, but plain-HTTP requests (getStationList, feedback, ...)
always go to port 80, which a test cannot bind portably. So pianobar is
configured with control_proxy = http://127.0.0.1:<port>: plain requests then
arrive here in proxy form (absolute URI) and HTTPS requests arrive as
"CONNECT host:port", which this server answers and then upgrades to TLS with a
throwaway certificate (generated by scripts/e2e-fake.sh at run time, passed
via --cert/--key, trusted by pianobar through ca_bundle). Audio is fetched by
pianobar's decoder directly from http://127.0.0.1:<port>/audio/<n>.mp3.

Requests are Blowfish-ECB encrypted hex (see src/libpiano/crypt.c). The keys
are made up and shared with pianobar through its config (encrypt_password =
--outkey, decrypt_password = --inkey). Python has no Blowfish in the standard
library, so a small implementation lives below; its constants (the hex digits
of pi) are computed at start-up.
"""

import argparse
